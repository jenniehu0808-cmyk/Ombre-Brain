"""Bundle common.py + mod_*.py + main.py + spec.json into ONE self-contained Blender script.

Usage: venv/bin/python make_single_file.py OUT.py [module names in build order]
The bundle keeps every source file verbatim and executes each one as a real module object
(registered in sys.modules), so 'from common import *' / 'import mod_body' keep working and
nothing is renamed. spec.json is embedded and written next to the outputs at start-up.
"""
import sys, os, json, re

WORK = os.path.dirname(os.path.abspath(__file__))
out = sys.argv[1]
modules = sys.argv[2:] or ['mod_body', 'mod_portico', 'mod_domes', 'mod_statues_site', 'mod_look']

def read(name):
    with open(os.path.join(WORK, name), encoding='utf-8') as f:
        return f.read()

def strip_main_block(src):
    """Remove a trailing `if __name__ == '__main__':` block (module self-tests)."""
    m = re.search(r"^if __name__\s*==\s*['\"]__main__['\"]\s*:\s*$", src, flags=re.M)
    return src[:m.start()].rstrip() + '\n' if m else src

sources = {'common': read('common.py')}
for name in modules:
    sources[name] = strip_main_block(read(name + '.py'))
sources['main'] = read('main.py')
spec = json.load(open(os.path.join(WORK, 'spec.json')))

bundle = f'''#!/usr/bin/env python
# -*- coding: utf-8 -*-
"""
Helsinki Cathedral at sunset — a procedural Blender model (single-file bundle).

How to run
  * Blender GUI: Scripting workspace -> Text -> Open this file -> Run Script (Alt+P).
    WARNING: the current scene is replaced (factory empty scene) by the cathedral.
    By default the GUI run only BUILDS the model and sets camera, sun, sky and render settings
    (1536x2048, 256 samples, Cycles) - press F12 to render, or set RENDER_ON_RUN = True below to
    render immediately (the UI is blocked while rendering; 5-20 min on a CPU). Outputs go to
    ~/helsinki_cathedral_out/ (set the CATHEDRAL_OUT environment variable to change that).
  * Command line (renders by default):
      blender -b -P helsinki_cathedral.py -- --res 1536 2048 --samples 256 --out render.png --blend scene.blend
  * Plain Python with the bpy wheel (pip install bpy):
      python helsinki_cathedral.py --res 1536 2048 --samples 256 --out render.png
  Options: --res W H  --samples N  --out file.png  --blend file.blend  --aerial [--aerial-out file.png]  --no-render

Cycles only (EEVEE is not supported), CPU rendering is fine. Written for Blender 5.x (tested on 5.2 LTS);
4.2+ should work (sky node fallback included) but is untested.
Generated by make_single_file.py from common.py, {', '.join(n + '.py' for n in modules)}, main.py and spec.json.
"""
import sys, os, json, types

RENDER_ON_RUN = 'auto'      # 'auto': render when headless (blender -b / python), build only in the Blender GUI
DEFAULT_RES = (1536, 2048)
DEFAULT_SAMPLES = 256
OUT_DIR = os.environ.get('CATHEDRAL_OUT', os.path.join(os.path.expanduser('~'), 'helsinki_cathedral_out'))
os.makedirs(OUT_DIR, exist_ok=True)

SPEC_JSON = {json.dumps(json.dumps(spec, ensure_ascii=False, indent=1))}

SOURCES = {{}}
'''
for name, src in sources.items():
    bundle += f"SOURCES[{name!r}] = {src!r}\n\n"

bundle += '''
def _load(name):
    """Execute an embedded source file as a real module (so cross-imports keep working)."""
    if name in sys.modules and getattr(sys.modules[name], '__cathedral_bundle__', False):
        return sys.modules[name]
    m = types.ModuleType(name)
    m.__file__ = os.path.join(OUT_DIR, name + '.py')
    m.__cathedral_bundle__ = True
    sys.modules[name] = m
    exec(compile(SOURCES[name], m.__file__, 'exec'), m.__dict__)
    return m

def run():
    import bpy
    # spec.json lives next to the outputs; common.load_spec() reads it from there
    with open(os.path.join(OUT_DIR, 'spec.json'), 'w', encoding='utf-8') as f:
        f.write(SPEC_JSON)
    # command-line arguments: inside the Blender binary only what follows '--' is ours
    in_blender_binary = not sys.argv[0].endswith('.py')
    if in_blender_binary:
        sys.argv = ['helsinki_cathedral.py'] + (sys.argv[sys.argv.index('--') + 1:] if '--' in sys.argv else [])
    args = sys.argv[1:]
    headless = bpy.app.background or not in_blender_binary
    do_render = (RENDER_ON_RUN == 'auto' and headless) or RENDER_ON_RUN is True
    if '--res' not in args:
        args += ['--res', str(DEFAULT_RES[0]), str(DEFAULT_RES[1])]
    if '--samples' not in args:
        args += ['--samples', str(DEFAULT_SAMPLES)]
    if '--out' not in args:
        args += ['--out', os.path.join(OUT_DIR, 'helsinki_cathedral_sunset.png')]
    if '--blend' not in args and headless:
        args += ['--blend', os.path.join(OUT_DIR, 'helsinki_cathedral.blend')]
    if '--no-compare' not in args:
        args += ['--no-compare']
    if not do_render and '--no-render' not in args:
        args += ['--no-render']
    sys.argv = [sys.argv[0]] + args
    print('[bundle] arguments:', ' '.join(args))
    common = _load('common')
    for name in SOURCES:
        if name.startswith('mod_'):
            _load(name)
    main = _load('main')
    main.main()
    if not do_render:
        print('[bundle] model built. Press F12 to render (settings are in place), or set RENDER_ON_RUN = True.')

run()
'''
with open(out, 'w', encoding='utf-8') as f:
    f.write(bundle)
print('wrote', out, len(bundle) // 1024, 'KB; modules:', ', '.join(sources))
